import { Paths, File } from 'expo-file-system';
import * as Sharing from 'expo-sharing';
import { getRecords, exportAllData } from './db';

const VALID_TABLES = ['wound_records', 'ostomy_records', 'intake_output', 'vitals', 'compression_measurements'] as const;
type ValidTable = typeof VALID_TABLES[number];

async function writeTextFile(filename: string, content: string): Promise<string> {
  const file = new File(Paths.document, filename);
  // SDK 57: must create file first on iOS, otherwise writableStream fails
  await file.create({ overwrite: true });
  const writer = file.writableStream().getWriter();
  try {
    await writer.write(new TextEncoder().encode(content));
    await writer.close();
  } catch (e) {
    writer.abort();
    throw e;
  }
  return file.uri;
}

export async function exportToCSV(table: string, filename: string): Promise<string> {
  if (!VALID_TABLES.includes(table as ValidTable)) {
    throw new Error(`Invalid table: ${table}`);
  }
  const records = await getRecords(table, 10000);
  if (records.length === 0) throw new Error('No records to export');

  const headers = Object.keys(records[0]);
  const csvRows = [
    headers.join(','),
    ...records.map(r => headers.map(h => `"${String(r[h] ?? '').replace(/"/g, '""')}"`).join(',')),
  ];
  const csv = csvRows.join('\n');
  return await writeTextFile(`${filename}.csv`, csv);
}

export async function exportBackup(): Promise<string> {
  const data = await exportAllData();
  const ts = new Date().toISOString().slice(0, 10);
  return await writeTextFile(`emis_medical_backup_${ts}.json`, data);
}

export async function shareFile(uri: string, mimeType = 'text/csv') {
  if (!(await Sharing.isAvailableAsync())) {
    throw new Error('Sharing not available on this device');
  }
  let UTI = 'public.comma-separated-values-text';
  if (mimeType === 'application/json') UTI = 'public.json';
  else if (mimeType === 'text/plain') UTI = 'public.plain-text';
  await Sharing.shareAsync(uri, {
    mimeType,
    dialogTitle: 'Share medical records',
    UTI,
  });
}

export async function generateDoctorSummary(): Promise<string> {
  const [wounds, ostomy, io, vitals, compression] = await Promise.all([
    getRecords('wound_records', 10000),
    getRecords('ostomy_records', 10000),
    getRecords('intake_output', 10000),
    getRecords('vitals', 10000),
    getRecords('compression_measurements', 10000),
  ]);

  let summary = 'EMIS+ Health Records Summary\n';
  summary += `Generated: ${new Date().toLocaleString('en-SG')}\n\n`;
  summary += `=== Wound Records (${wounds.length}) ===\n`;
  wounds.forEach(w => {
    summary += `${w.date}: ${w.location} - ${w.length}x${w.width}x${w.depth}cm, exudate: ${w.exudate}\n`;
    if (w.notes) summary += `  Notes: ${w.notes}\n`;
  });
  summary += `\n=== Ostomy Records (${ostomy.length}) ===\n`;
  ostomy.forEach(o => {
    summary += `${o.date}: ${o.output_type} - ${o.output_amount}ml${o.appliance_change ? ' (appliance changed)' : ''}\n`;
  });
  summary += `\n=== Intake & Output (${io.length}) ===\n`;
  io.forEach(r => {
    summary += `${r.date} ${r.time}: ${r.type} - ${r.category} ${r.amount}ml\n`;
  });
  summary += `\n=== Vitals (${vitals.length}) ===\n`;
  vitals.forEach(v => {
    const parts = [];
    if (v.systolic) parts.push(`BP ${v.systolic}/${v.diastolic}`);
    if (v.heart_rate) parts.push(`HR ${v.heart_rate}`);
    if (v.temperature) parts.push(`Temp ${v.temperature}C`);
    if (v.oxygen_saturation) parts.push(`SpO2 ${v.oxygen_saturation}%`);
    if (v.blood_sugar) parts.push(`BS ${v.blood_sugar}${v.blood_sugar_unit || 'mmol/L'}`);
    if (v.weight) parts.push(`Wt ${v.weight}kg`);
    summary += `${v.date} ${v.time}: ${parts.join(', ')}\n`;
  });
  summary += `\n=== Compression Measurements (${compression.length}) ===\n`;
  compression.forEach(c => {
    summary += `${c.date}: ${c.leg} leg - ankle ${c.ankle}cm, calf ${c.calf}cm, thigh ${c.thigh || 'N/A'}cm => ${c.recommended_size || 'size TBD'}\n`;
  });
  summary += '\n--- This report was generated by the EMIS+ app. All data stored locally on device. ---';

  return await writeTextFile('emis_doctor_summary.txt', summary);
}

// Compression stocking size calculator
// Uses AND logic: both ankle AND calf must fit the size range
export function calculateCompressionSize(ankle: number, calf: number, thigh?: number): string {
  if (!Number.isFinite(ankle) || !Number.isFinite(calf) || ankle <= 0 || calf <= 0) {
    return 'Invalid measurements';
  }
  // Standard compression stocking sizing (ankle circumference is primary)
  if (ankle >= 19 && ankle < 22 && calf >= 27 && calf < 33) return 'S';
  if (ankle >= 22 && ankle < 25 && calf >= 33 && calf < 38) return 'M';
  if (ankle >= 25 && ankle < 28 && calf >= 38 && calf < 43) return 'L';
  if (ankle >= 28 && ankle < 31 && calf >= 43 && calf < 48) return 'XL';
  if (ankle >= 31 || calf >= 48) return 'XXL - please consult specialist';
  // Measurements fall between sizes
  return 'Between sizes - please consult specialist for exact fit';
}
